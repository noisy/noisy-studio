"""Put text into whatever text field has focus, in any app (dictate anywhere).

How: save the general pasteboard, put the text on it, post Cmd+V as a
synthetic key event, then put the saved pasteboard back.

Why paste and not the alternatives:

- Accessibility insertion (setting kAXSelectedTextAttribute on the focused
  AXUIElement) only works where the app implements it well. Native Cocoa
  fields do; terminals (Terminal, iTerm2, Ghostty, kitty) do not, and in
  browsers and Electron apps it writes behind the page's back - no DOM
  input event, so a React or Vue textarea never sees the change.
- Typing the text as Unicode key events reaches every app, but one key at
  a time: slow for a long sentence, interpreted by key bindings (vim in
  normal mode, shell shortcuts), and a newline is Enter, which runs a
  half-dictated command in a terminal.
- Cmd+V is the one text action every field supports. It is a single,
  atomic, one-step-undo insertion, and terminals use bracketed paste, so a
  multi-line transcript is inserted, not executed.

The cost is the clipboard. It is restored afterwards (every item and every
type), unless the user copied something new in the meantime. The temporary
text is marked transient (nspasteboard.org) so clipboard managers skip it.

Permission: posting synthetic events needs Accessibility (System Settings >
Privacy & Security > Accessibility) for the process that runs the daemon.
Like Input Monitoring (#97), it is never requested at boot: only when the
user binds the dictate key, presses it, or presses the grant button.
"""

from __future__ import annotations

import time
from dataclasses import dataclass
from typing import Callable

V_KEYCODE = 9  # kVK_ANSI_V
# The target app reads the pasteboard while it handles Cmd+V, asynchronously
# to us. Restoring too early pastes the OLD clipboard; this leaves room for a
# busy Electron app without making back-to-back dictations feel stuck.
RESTORE_DELAY_SECONDS = 0.5
# Pause between key down and key up: some apps ignore a zero-length press.
KEY_PRESS_SECONDS = 0.01
STRING_TYPE = "public.utf8-plain-text"
# nspasteboard.org markers: clipboard managers do not record these items.
TRANSIENT_TYPES = ("org.nspasteboard.TransientType", "org.nspasteboard.AutoGeneratedType")


def _quartz():
    """The Quartz bridge, or None off macOS. One seam for the tests."""
    try:
        import Quartz  # noqa: PLC0415

        return Quartz
    except ImportError:
        return None


def _appkit():
    try:
        import AppKit  # noqa: PLC0415

        return AppKit
    except ImportError:
        return None


def accessibility_status(quartz=None) -> str:
    """"granted" | "missing" | "unavailable" (non-macOS or old pyobjc)."""
    quartz = quartz if quartz is not None else _quartz()
    if quartz is None or not hasattr(quartz, "CGPreflightPostEventAccess"):
        return "unavailable"
    return "granted" if quartz.CGPreflightPostEventAccess() else "missing"


def request_accessibility() -> str:
    """Ask macOS (it shows its prompt once; a refusal must be undone in
    System Settings). Returns the status afterwards."""
    quartz = _quartz()
    if quartz is None or not hasattr(quartz, "CGRequestPostEventAccess"):
        return "unavailable"
    return "granted" if quartz.CGRequestPostEventAccess() else "missing"


class InsertionError(RuntimeError):
    pass


@dataclass(frozen=True)
class Insertion:
    app: str  # the frontmost app the text was pasted into ("" when unknown)


class PasteInserter:
    """Inserts text through the pasteboard and a synthetic Cmd+V."""

    def __init__(
        self,
        appkit=None,
        quartz=None,
        sleep: Callable[[float], None] = time.sleep,
    ) -> None:
        self._appkit = appkit if appkit is not None else _appkit()
        self._quartz = quartz if quartz is not None else _quartz()
        self._sleep = sleep

    def insert(self, text: str) -> Insertion:
        if self._appkit is None or self._quartz is None:
            raise InsertionError("text insertion needs macOS")
        if accessibility_status(self._quartz) != "granted":
            raise InsertionError("Accessibility permission missing")
        pasteboard = self._appkit.NSPasteboard.generalPasteboard()
        saved = _save_items(pasteboard)
        ours = _put_text(pasteboard, text)
        try:
            self._press_paste()
            self._sleep(RESTORE_DELAY_SECONDS)
        finally:
            # The user may have copied something meanwhile: theirs wins.
            if pasteboard.changeCount() == ours:
                _restore_items(self._appkit, pasteboard, saved)
        return Insertion(app=self._frontmost_app())

    def _press_paste(self) -> None:
        quartz = self._quartz
        source = quartz.CGEventSourceCreate(quartz.kCGEventSourceStateHIDSystemState)
        for down in (True, False):
            event = quartz.CGEventCreateKeyboardEvent(source, V_KEYCODE, down)
            # Explicit flags: modifiers of the dictate chord that are still
            # physically held must not turn Cmd+V into Cmd+Shift+V.
            quartz.CGEventSetFlags(event, quartz.kCGEventFlagMaskCommand)
            quartz.CGEventPost(quartz.kCGHIDEventTap, event)
            if down:
                self._sleep(KEY_PRESS_SECONDS)

    def _frontmost_app(self) -> str:
        try:
            app = self._appkit.NSWorkspace.sharedWorkspace().frontmostApplication()
            return str(app.localizedName() or "") if app is not None else ""
        except Exception:  # noqa: BLE001 - a name for the log, never essential
            return ""


def _save_items(pasteboard) -> list[dict[str, object]]:
    """Every item with every type's raw data, so rich content survives."""
    saved = []
    for item in pasteboard.pasteboardItems() or []:
        types = {}
        for kind in item.types() or []:
            data = item.dataForType_(kind)
            if data is not None:
                types[str(kind)] = data
        if types:
            saved.append(types)
    return saved


def _put_text(pasteboard, text: str) -> int:
    pasteboard.clearContents()
    pasteboard.setString_forType_(text, STRING_TYPE)
    for marker in TRANSIENT_TYPES:
        pasteboard.setString_forType_("", marker)
    return pasteboard.changeCount()


def _restore_items(appkit, pasteboard, saved: list[dict[str, object]]) -> None:
    pasteboard.clearContents()
    if not saved:
        return
    items = []
    for types in saved:
        item = appkit.NSPasteboardItem.alloc().init()
        for kind, data in types.items():
            item.setData_forType_(data, kind)
        items.append(item)
    pasteboard.writeObjects_(items)
